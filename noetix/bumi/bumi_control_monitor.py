"""Read Bumi high-level control requests without publishing robot commands.

The SDK bundles CycloneDDS, but its Python API exposes a writer only. This
module discovers the vendor's existing command type at runtime and runs the
reader in a separate process from ROS's Fast DDS implementation. It never
creates a DDS writer. The descriptor check is deliberately exact: an unknown
firmware type must fail closed instead of being interpreted as the old layout.
"""

from __future__ import annotations

import ctypes as ct
import json
import math
import os
import signal
import struct
import sys
import time

TOPIC = "Control_Cmd_Topic"
TYPE = "RobotControlCmd::ControlCmd"
FRAME_PREFIX = "BUMI_CONTROL_MONITOR "
# Generated by the bundled CycloneDDS 0.11 type discovery on the tested Bumi.
# double axes[3] @ 0, uint32 action @ 24, uint16 data @ 28.
EXPECTED_OPS = (0x01080402, 0, 3, 0x01030004, 24, 0x01020000, 28, 0)
_DIRECTION_NAMES_ZH = {
    "forward": "前进", "backward": "后退", "left": "左移", "right": "右移",
    "turn_left": "左转", "turn_right": "右转",
}


def decode_sample(raw: bytes, publisher: str, received_ms: int) -> dict:
    """Decode the validated C-memory layout, retaining the publisher identity."""
    if len(raw) != 32:
        raise ValueError("unexpected control sample size")
    axes = struct.unpack_from("=3d", raw)
    if not all(math.isfinite(value) for value in axes):
        raise ValueError("non-finite command axis")
    action = struct.unpack_from("=I", raw, 24)[0]
    data = struct.unpack_from("=H", raw, 28)[0]
    # HighController::publish_cmd stores z, x, y in axes[0], [1], [2].
    return {
        "axes": list(axes), "action_code": action, "data": data,
        "publisher_guid": publisher, "received_at_ms": received_ms,
    }


def describe_command(sample: dict, deadband: float = 0.05) -> dict:
    """Describe observed inputs; do not claim actual motion or App identity."""
    yaw, forward, lateral = sample["axes"]
    directions = []
    if forward > deadband:
        directions.append("forward")
    elif forward < -deadband:
        directions.append("backward")
    if lateral > deadband:
        directions.append("left")
    elif lateral < -deadband:
        directions.append("right")
    if yaw > deadband:
        directions.append("turn_left")
    elif yaw < -deadband:
        directions.append("turn_right")
    description = ("方向控制请求：" + "、".join(_DIRECTION_NAMES_ZH[item] for item in directions)
                   if directions else "方向控制量处于中位或低于死区")
    return {
        "forward": forward, "lateral": lateral, "yaw": yaw,
        "directions": directions, "description_zh": description,
        "axes_neutral": not directions,
        "action_code": sample["action_code"], "data": sample["data"],
        "publisher_guid": sample["publisher_guid"],
        "received_at_ms": sample["received_at_ms"],
        "origin": "unknown", "execution_status": "unknown",
    }


class CommandState:
    """A recent observation is different from a connected or idle controller."""

    def __init__(self, stale_after_s: float, deadband: float):
        self.stale_after_s = stale_after_s
        self.deadband = deadband
        self.reader_ready = False
        self.matched_publishers = 0
        self.last = None
        self.last_monotonic = None
        self.by_publisher = {}
        self.error = None

    def ready(self, matched_publishers: int) -> None:
        self.reader_ready = True
        self.matched_publishers = max(0, int(matched_publishers))
        self.error = None

    def unavailable(self, error: str | None = None) -> None:
        self.reader_ready = False
        self.matched_publishers = 0
        self.last = None
        self.last_monotonic = None
        self.by_publisher.clear()
        self.error = error

    def observe(self, sample: dict, now: float) -> dict:
        command = describe_command(sample, self.deadband)
        received = sample.get("received_monotonic_s", now)
        if not isinstance(received, (int, float)) or not math.isfinite(received) or received < 0:
            raise ValueError("invalid monotonic receipt time")
        received = min(now, received)
        publisher = command["publisher_guid"]
        previous = self.by_publisher.get(publisher)
        if previous is None or received >= previous[1]:
            self.by_publisher[publisher] = (command, received)
        if self.last_monotonic is None or received >= self.last_monotonic:
            self.last, self.last_monotonic = command, received
        # A long-running robot can see many transient SDK clients.
        self.by_publisher = {key: value for key, value in self.by_publisher.items()
                             if now - value[1] <= max(60.0, self.stale_after_s)}
        if len(self.by_publisher) > 64:
            oldest = min(self.by_publisher, key=lambda key: self.by_publisher[key][1])
            del self.by_publisher[oldest]
        return command

    def snapshot(self, now: float) -> dict:
        age = None if self.last_monotonic is None else max(0.0, now - self.last_monotonic)
        fresh = bool(self.reader_ready and age is not None and age <= self.stale_after_s)
        recent = []
        if self.reader_ready:
            for command, received in sorted(self.by_publisher.values(), key=lambda item: item[1], reverse=True):
                publisher_age = max(0.0, now - received)
                if publisher_age <= self.stale_after_s:
                    recent.append({**command, "age_s": round(publisher_age, 3)})
        if not self.reader_ready:
            state = "unavailable"
        elif fresh:
            state = "observed"
        else:
            state = "no_recent_command"
        return {
            "state": state, "fresh": fresh,
            "reader_ready": self.reader_ready,
            "matched_publishers": self.matched_publishers,
            "command": self.last if fresh else None,
            "recent_commands": recent,
            "last_received_at_ms": self.last["received_at_ms"] if self.last else None,
            "age_s": round(age, 3) if age is not None else None,
            "error": self.error,
        }


_void = ct.c_void_p
_int = ct.c_int32
_uint = ct.c_uint32


class _SampleInfo(ct.Structure):
    _fields_ = [
        ("sample_state", _int), ("view_state", _int), ("instance_state", _int),
        ("valid_data", ct.c_bool), ("source_timestamp", ct.c_int64),
        ("instance_handle", ct.c_uint64), ("publication_handle", ct.c_uint64),
        ("disposed", _uint), ("no_writers", _uint), ("sample_rank", _uint),
        ("generation_rank", _uint), ("absolute_generation_rank", _uint),
    ]


class _Endpoint(ct.Structure):
    _fields_ = [
        ("key", ct.c_ubyte * 16), ("participant", ct.c_ubyte * 16),
        ("handle", ct.c_uint64), ("topic", ct.c_char_p),
        ("type_name", ct.c_char_p), ("qos", _void),
    ]


class _Metadata(ct.Structure):
    _fields_ = [("data", _void), ("size", _uint)]


class _Descriptor(ct.Structure):
    _fields_ = [
        ("size", _uint), ("align", _uint), ("flags", _uint), ("nkeys", _uint),
        ("name", ct.c_char_p), ("keys", _void), ("nops", _uint),
        ("ops", ct.POINTER(_uint)), ("meta", ct.c_char_p),
        ("type_info", _Metadata), ("type_mapping", _Metadata), ("representation", _uint),
    ]


def _validate_descriptor(address: _void) -> None:
    descriptor = ct.cast(address, ct.POINTER(_Descriptor)).contents
    if (sys.byteorder != "little" or descriptor.size != 32 or descriptor.align != 8
            or descriptor.name != TYPE.encode() or descriptor.nops != len(EXPECTED_OPS)
            or not descriptor.ops):
        raise RuntimeError("unsupported Bumi command type layout")
    if tuple(descriptor.ops[index] for index in range(descriptor.nops)) != EXPECTED_OPS:
        raise RuntimeError("unsupported Bumi command serialization layout")


class _CycloneReader:
    """CycloneDDS C binding for only the reader and discovery operations."""

    def __init__(self):
        self.lib = ct.CDLL("libddsc.so")
        self.participant = 0
        self.descriptor = _void()
        self.reader = 0
        self._publishers = {}
        self._bind()

    def _fn(self, name, args, result=_int):
        fn = getattr(self.lib, name)
        fn.argtypes, fn.restype = args, result
        return fn

    def _bind(self):
        self.create_participant = self._fn("dds_create_participant", [_uint, _void, _void])
        self.create_reader = self._fn("dds_create_reader", [_int, _int, _void, _void])
        self.take = self._fn("dds_take", [_int, ct.POINTER(_void), _void, ct.c_size_t, _uint])
        self.return_loan = self._fn("dds_return_loan", [_int, ct.POINTER(_void), _int])
        self.endpoint_type = self._fn("dds_builtintopic_get_endpoint_type_info", [_void, ct.POINTER(_void)])
        self.make_descriptor = self._fn("dds_create_topic_descriptor", [_int, _int, _void, ct.c_int64, ct.POINTER(_void)])
        self.create_topic = self._fn("dds_create_topic", [_int, _void, ct.c_char_p, _void, _void])
        self.matched = self._fn("dds_get_matched_publications", [_int, _void, ct.c_size_t])
        self.matched_data = self._fn("dds_get_matched_publication_data", [_int, ct.c_uint64], _void)
        self.free_endpoint = self._fn("dds_builtintopic_free_endpoint", [_void], None)
        self.free_descriptor = self._fn("dds_delete_topic_descriptor", [_void])
        self.delete = self._fn("dds_delete", [_int])

    @staticmethod
    def _check(value: int, what: str) -> int:
        if value <= 0:
            raise RuntimeError(f"{what} failed ({value})")
        return value

    def _read(self, reader, callback):
        buffer = (_void * 64)()
        info = (_SampleInfo * 64)()
        count = self.take(reader, buffer, ct.byref(info), 64, 64)
        if count < 0:
            raise RuntimeError(f"DDS read failed ({count})")
        try:
            for index in range(count):
                if info[index].valid_data and buffer[index]:
                    callback(buffer[index], info[index])
        finally:
            if count:
                self.return_loan(reader, buffer, count)

    def open(self, cancelled):
        self.participant = self._check(self.create_participant(0xFFFFFFFF, None, None), "participant")
        discovery = self._check(self.create_reader(self.participant, 0x7FFF0003, None, None), "discovery reader")

        def discovered(address, _info):
            if self.descriptor.value:
                return
            endpoint = ct.cast(address, ct.POINTER(_Endpoint)).contents
            if endpoint.topic != TOPIC.encode() or endpoint.type_name != TYPE.encode():
                return
            info = _void()
            if self.endpoint_type(address, ct.byref(info)) != 0 or not info.value:
                return
            result = self.make_descriptor(0, self.participant, info, 3_000_000_000, ct.byref(self.descriptor))
            if result != 0:
                self.descriptor = _void()
            # The bundled CycloneDDS 0.11 frees this discovery metadata with
            # the participant. Explicit dds_free_typeinfo, whether before or
            # after participant deletion, causes a double free on the Bumi.
            # The isolated worker bounds its lifetime even on failed setup.

        deadline = time.monotonic() + 15.0
        while not self.descriptor.value and time.monotonic() < deadline and not cancelled():
            self._read(discovery, discovered)
            time.sleep(0.1)
        if not self.descriptor.value:
            raise RuntimeError("control topic type was not discovered")
        _validate_descriptor(self.descriptor)
        topic = self._check(self.create_topic(self.participant, self.descriptor, TOPIC.encode(), None, None), "topic")
        self.reader = self._check(self.create_reader(self.participant, topic, None, None), "command reader")

    def count(self):
        count = self.matched(self.reader, None, 0)
        if count < 0:
            raise RuntimeError(f"DDS publisher discovery failed ({count})")
        return count

    def _publisher(self, handle):
        if handle not in self._publishers:
            endpoint = self.matched_data(self.reader, handle)
            if not endpoint:
                return f"unknown-{handle}"
            try:
                self._publishers[handle] = bytes(ct.cast(endpoint, ct.POINTER(_Endpoint)).contents.key).hex()
            finally:
                self.free_endpoint(endpoint)
        return self._publishers[handle]

    def read_samples(self, callback):
        def received(address, info):
            sample = decode_sample(ct.string_at(address, 32), self._publisher(info.publication_handle),
                                   time.time_ns() // 1_000_000)
            sample["received_monotonic_s"] = time.monotonic()
            callback(sample)
        self._read(self.reader, received)

    def close(self):
        if self.participant > 0:
            self.delete(self.participant)
            self.participant = 0
        if self.descriptor.value:
            self.free_descriptor(self.descriptor)
            self.descriptor = _void()


def _emit(frame):
    print(FRAME_PREFIX + json.dumps(frame, ensure_ascii=False, allow_nan=False), flush=True)


def run_worker():
    stopping = False

    # If the vendor library crashes, do not leave a core dump in the container.
    try:
        import resource
        resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    except (ImportError, OSError, ValueError):
        pass

    def stop(_signum, _frame):
        nonlocal stopping
        stopping = True

    signal.signal(signal.SIGTERM, stop)
    signal.signal(signal.SIGINT, stop)
    reader = _CycloneReader()
    try:
        reader.open(lambda: stopping)
        _emit({"kind": "ready", "matched_publishers": reader.count()})
        heartbeat = time.monotonic()
        while not stopping:
            reader.read_samples(lambda sample: _emit({"kind": "sample", "sample": sample}))
            now = time.monotonic()
            if now >= heartbeat:
                _emit({"kind": "heartbeat", "matched_publishers": reader.count()})
                heartbeat = now + 1.0
            time.sleep(0.02)
    finally:
        reader.close()


if __name__ == "__main__":
    if sys.argv[1:] != ["--worker"]:
        raise SystemExit("use --worker")
    try:
        run_worker()
    except Exception as exc:
        _emit({"kind": "error", "error": str(exc)[:300]})
        raise SystemExit(1)
